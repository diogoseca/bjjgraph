export function framesFor(item) {
  if (item.frames) return item.frames;
  let offset = 0;
  return item.chapters.flatMap((chapter, chapterIndex) => {
    const source = useCases.find((entry) => entry.id === chapter.caseId);
    if (!source) throw new Error(`Unknown Forward use case: ${chapter.caseId}`);
    const frames = source.frames.map((entry, stepIndex) => ({
      ...entry,
      at: offset + entry.at,
      chapter: chapter.label,
      chapterIndex,
      sourceCaseId: source.id,
      sourceCaseTitle: source.title,
      journeyStep: stepIndex,
    }));
    offset += (source.frames.at(-1)?.at || 0) + 420;
    return frames;
  });
}
