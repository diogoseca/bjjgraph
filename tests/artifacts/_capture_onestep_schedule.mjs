// THE ONE-STEP CLIENT, CAPTURED (v1.305.0, LATE1): the schedule every build from v1.281.3 to v1.304.0 runs, where a late
// right answer earns exactly one step (an open tab or an installed copy still runs it, and it is the rule the late answer's
// doubled wait was added to). Writes tests/artifacts/schedule_onestep_client.json: the exact source text, cut out of git's own
// copy of each file at the named revision (never re-typed), with each file's sha256: knowledge-profile's ladder and its whole
// schedule block (the due day, the step, the line, the pair's reader, the early walk, the writer and the srs pull merge), and
// the rating's row reading (`ngRatingRecall` with the exact-interval copy it calls). tests/schedule_late.test.mjs runs it
// against the rows v1.305.0 writes (an older build reads them and climbs), compares every early and every wrong answer with it
// (unchanged, byte for byte), and the path searches of tests/schedule_rung.test.mjs and tests/schedule_linear.test.mjs use
// it to tell the histories the doubled wait never decided from the ones it did. Since LATEFIX1 (the reader of PR #472, F1) it
// also holds that build's moves merge (`ngProgressMergeMoves` with the exact-interval reader it calls, progress-owner.src.js),
// the merge that keeps a cloud row's cells after the pair: tests/schedule_late_mark.test.mjs runs an older build's chain of
// answers through it. The clients before it are
// tests/artifacts/schedule_lin1_client.json (v1.281.0), schedule_prev_client.json (v1.279.0 to v1.280.2) and
// schedule_old_client.json (v1.278.2). Run once from the repo root:
//   node tests/artifacts/_capture_onestep_schedule.mjs [rev]
// Not a test: `node --test tests/*.test.mjs` does not collect it.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
const rev = process.argv[2] || "0e3fcf1ad";
const show = (path) => execFileSync("git", ["show", `${rev}:${path}`], { encoding: "utf8", maxBuffer: 64 << 20 });
const sha = (s) => createHash("sha256").update(s).digest("hex");
const cut = (src, from, to, plus = 0) => {
  const a = src.indexOf(from), b = src.indexOf(to, a);
  if (a < 0 || b < 0) throw new Error(`${from} … ${to} not found at ${rev}`);
  return src.slice(a, b + plus).replace(/^export /gm, "");
};
const kp = show("neural/src/knowledge-profile.src.js"), rt = show("neural/src/rating.src.js"), po = show("neural/src/progress-owner.src.js");
const out = {
  note: "Generated by tests/artifacts/_capture_onestep_schedule.mjs from git's own copy of each file at the named revision; never edit by hand. tests/schedule_late.test.mjs runs this code as the one-step client (v1.281.3 to v1.304.0).",
  rev, version: JSON.parse(show("package.json")).version,
  knowledge: { sha256: sha(kp), ladder: cut(kp, "export const NG_KNOWLEDGE_INTERVALS", "})());", 6),
    schedule: cut(kp, "const NG_KNOWLEDGE_EPS", "export function ngKnowledgeApplyGrade(") },
  rating: { sha256: sha(rt),
    base: cut(rt, "export const NG_RATING_FADE", "export const NG_RATING_TABLE"),
    num: cut(rt, "function ngRatingNum(", "\n", 1),
    recall: cut(rt, "export function ngRatingRecall(", "\n}\n", 2),
    interval: cut(rt, "const NG_RATING_SCHED_LADDER", "/**\n * THE GAME, for one ruleset") },
  owner: { sha256: sha(po), mergeMoves: cut(po, "const NG_PROGRESS_SCHED_LADDER", "// THE ANSWERS A COPY HAS NOT YET DELIVERED") },
};
writeFileSync(new URL("./schedule_onestep_client.json", import.meta.url), JSON.stringify(out, null, 1) + "\n");
console.log("captured", rev, out.version, "ladder", out.knowledge.ladder.length, "schedule", out.knowledge.schedule.length,
  "rating", out.rating.base.length + out.rating.num.length + out.rating.recall.length + out.rating.interval.length);
