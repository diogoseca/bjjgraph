// and v1.252.0 (the tag v2026.11.09, production until 19 Nov) run it, and since v1.298.0 (LISTS-R Slice 2) v1.293.3 (the tag
// v2026.11.19) and v1.294.0 (the tag v2026.11.19.1, production since 19 Nov 17:41), with the one helper it calls, cut out of git's own copy of
// neural/src/progress-owner.src.js at each revision (never re-typed), with the file's sha256. Writes
// tests/artifacts/progress_validators.json. tests/schedule_rung.test.mjs runs every row the writer emits through each, so an
// older client accepts every blob this one writes (the reader of PR #426's finding 1: a negative pair day made every client
// reject the whole blob). Run once from the repo root:
//   node tests/artifacts/_capture_validators.mjs
// Not a test: `node --test tests/*.test.mjs` does not collect it.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
const sha = (s) => createHash("sha256").update(s).digest("hex");
const cut = (src, from, to, plus, rev) => {
  const a = src.indexOf(from), b = src.indexOf(to, a);
  if (a < 0 || b < 0) throw new Error(`${from} … not found at ${rev}`);
  return src.slice(a, b + plus).replace(/^export /gm, "");
};
const out = { note: "Generated by tests/artifacts/_capture_validators.mjs from git's own copy of each file at the named revision; never edit by hand.", clients: {} };
for (const [name, rev] of [["v1.280.4", "ed701b3b5"], ["v1.252.0", "v2026.11.09"], ["v1.293.3", "v2026.11.19"], ["v1.294.0", "v2026.11.19.1"]]) {
  const show = (path) => execFileSync("git", ["show", `${rev}:${path}`], { encoding: "utf8", maxBuffer: 64 << 20 });
  const po = show("neural/src/progress-owner.src.js");
  out.clients[name] = { rev, version: JSON.parse(show("package.json")).version, sha256: sha(po),
    validator: cut(po, "function ngProgressObject(", "\n", 1, rev) + cut(po, "export function ngProgressValidateBlob(", "\n}\n", 2, rev) };
}
writeFileSync(new URL("./progress_validators.json", import.meta.url), JSON.stringify(out, null, 1) + "\n");
for (const [k, v] of Object.entries(out.clients)) console.log("captured", k, v.rev, v.version, "validator", v.validator.length);
