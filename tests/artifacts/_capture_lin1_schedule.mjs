// owner's formula with one straight line from the card's own interval, anchors off the rungs). Writes
// tests/artifacts/schedule_lin1_client.json: the exact source text, cut out of git's own copy of each file at the named
// revision (never re-typed), with each file's sha256: knowledge-profile's ladder and its whole schedule block (the due day,
// the step, the line, the pair's reader, the writer and the srs pull merge, which the app's pull calls), progress-owner's
// reader copies and its moves merge, and the app's `_gradeMove` row line. tests/schedule_rung.test.mjs runs it against the
// rows v1.281.2 writes, and v1.281.2 against the rows it wrote. The clients before it are tests/artifacts/
// schedule_prev_client.json (v1.279.0 to v1.280.2) and schedule_old_client.json (v1.278.2). Run once from the repo root:
//   node tests/artifacts/_capture_lin1_schedule.mjs [rev]
// Not a test: `node --test tests/*.test.mjs` does not collect it.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
const rev = process.argv[2] || "23cc60174";
const show = (path) => execFileSync("git", ["show", `${rev}:${path}`], { encoding: "utf8", maxBuffer: 64 << 20 });
const sha = (s) => createHash("sha256").update(s).digest("hex");
const cut = (src, from, to, plus = 0) => {
  const a = src.indexOf(from), b = src.indexOf(to, a);
  if (a < 0 || b < 0) throw new Error(`${from} … ${to} not found at ${rev}`);
  return src.slice(a, b + plus).replace(/^export /gm, "");
};
const kp = show("neural/src/knowledge-profile.src.js"), po = show("neural/src/progress-owner.src.js"), app = show("neural/src/app.src.jsx");
const out = {
  note: "Generated by tests/artifacts/_capture_lin1_schedule.mjs from git's own copy of each file at the named revision; never edit by hand. tests/schedule_rung.test.mjs runs this code as the v1.281.0 client.",
  rev, version: JSON.parse(show("package.json")).version,
  knowledge: { sha256: sha(kp), ladder: cut(kp, "export const NG_KNOWLEDGE_INTERVALS", "})());", 6),
    schedule: cut(kp, "const NG_KNOWLEDGE_EPS", "export function ngKnowledgeApplyGrade(") },
  owner: { sha256: sha(po), mergeMoves: "" },
  app: { sha256: sha(app), gradeMove: cut(app, "row[k[1]] = ngKnowledgeScheduleRow(prior, ok, day, 4)", ";", 1) },
};
// the moves merge and the reader copies it calls: from the copies' ladder to the end of `ngProgressMergeMoves`
{ const a = po.indexOf("const NG_PROGRESS_SCHED_LADDER"), m = po.indexOf("export function ngProgressMergeMoves(", a), b = po.indexOf("\n}\n", m);
  if (a < 0 || m < 0 || b < 0) throw new Error(`the moves merge not found at ${rev}`);
  out.owner.mergeMoves = po.slice(a, b + 2).replace(/^export /gm, ""); }
writeFileSync(new URL("./schedule_lin1_client.json", import.meta.url), JSON.stringify(out, null, 1) + "\n");
console.log("captured", rev, out.version, "ladder", out.knowledge.ladder.length, "schedule", out.knowledge.schedule.length,
  "mergeMoves", out.owner.mergeMoves.length, "gradeMove", JSON.stringify(out.app.gradeMove));
