// THE PREVIOUS CLIENT, CAPTURED (v1.281.0, LIN1): the schedule an open tab or an installed copy of v1.279.0 to v1.280.2 still
// runs (the owner's ladder with v1.279.0's log-scale credit). Writes tests/artifacts/schedule_prev_client.json: the exact
// source text, cut out of git's own copy of each file at the named revision (never re-typed), with each file's sha256:
// knowledge-profile's ladder and its schedule block (writer, helpers and the srs pull merge, which the app's pull calls),
// progress-owner's moves merge, and the app's `_gradeMove` row line (which keeps a moves row's cells after the fourth, so it
// carries a v1.281.0 pair behind its own new due). tests/schedule_linear.test.mjs runs it against the rows v1.281.0 writes.
// The client before it (dev v1.278.2, production's text) is tests/artifacts/schedule_old_client.json. Run once from the repo root:
//   node tests/artifacts/_capture_prev_schedule.mjs [rev]
// Not a test: `node --test tests/*.test.mjs` does not collect it.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
const rev = process.argv[2] || "6325e7682";
const show = (path) => execFileSync("git", ["show", `${rev}:${path}`], { encoding: "utf8", maxBuffer: 64 << 20 });
const sha = (s) => createHash("sha256").update(s).digest("hex");
const cut = (src, from, to, plus = 0) => {
  const a = src.indexOf(from), b = src.indexOf(to, a);
  if (a < 0 || b < 0) throw new Error(`${from} … ${to} not found at ${rev}`);
  return src.slice(a, b + plus).replace(/^export /gm, "");
};
const kp = show("neural/src/knowledge-profile.src.js"), po = show("neural/src/progress-owner.src.js"), app = show("neural/src/app.src.jsx");
const fn = (src, name) => cut(src, `export function ${name}(`, "\n}\n", 2);
const out = {
  note: "Generated by tests/artifacts/_capture_prev_schedule.mjs from git's own copy of each file at the named revision; never edit by hand. tests/schedule_linear.test.mjs runs this code as the previous client.",
  rev, version: JSON.parse(show("package.json")).version,
  knowledge: { sha256: sha(kp), ladder: cut(kp, "export const NG_KNOWLEDGE_INTERVALS", "})());", 6),
    schedule: cut(kp, "export function ngKnowledgeInterval(", "export function ngKnowledgeApplyGrade(") },
  owner: { sha256: sha(po), mergeMoves: fn(po, "ngProgressMergeMoves") },
  app: { sha256: sha(app), gradeMove: cut(app, "row[k[1]] = ngKnowledgeScheduleRow(prior, ok, day)", ";", 1) },
};
writeFileSync(new URL("./schedule_prev_client.json", import.meta.url), JSON.stringify(out, null, 1) + "\n");
console.log("captured", rev, out.version, "ladder", out.knowledge.ladder.length, "schedule", out.knowledge.schedule.length,
  "mergeMoves", out.owner.mergeMoves.length, "gradeMove", JSON.stringify(out.app.gradeMove));
